CREATE TABLE "TASK_DELIVERABLE_DEFINITION" (
    "definition_id" SERIAL NOT NULL,
    "task_id" INTEGER NOT NULL,
    "title" VARCHAR(255) NOT NULL,
    "description" TEXT,
    "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "TASK_DELIVERABLE_DEFINITION_pkey" PRIMARY KEY ("definition_id")
);

CREATE TABLE "DELIVERABLE_SUBMISSION_ITEM" (
    "task_id" INTEGER NOT NULL,
    "deliverable_no" INTEGER NOT NULL,
    "definition_id" INTEGER NOT NULL,

    CONSTRAINT "DELIVERABLE_SUBMISSION_ITEM_pkey" PRIMARY KEY ("task_id", "deliverable_no", "definition_id")
);

CREATE UNIQUE INDEX "TASK_DELIVERABLE_DEFINITION_task_id_definition_id_key"
    ON "TASK_DELIVERABLE_DEFINITION"("task_id", "definition_id");
CREATE INDEX "TASK_DELIVERABLE_DEFINITION_task_id_idx"
    ON "TASK_DELIVERABLE_DEFINITION"("task_id");
CREATE INDEX "DELIVERABLE_SUBMISSION_ITEM_task_id_definition_id_idx"
    ON "DELIVERABLE_SUBMISSION_ITEM"("task_id", "definition_id");

ALTER TABLE "TASK_DELIVERABLE_DEFINITION"
    ADD CONSTRAINT "TASK_DELIVERABLE_DEFINITION_task_id_fkey"
    FOREIGN KEY ("task_id") REFERENCES "TASKS"("task_id") ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE "DELIVERABLE_SUBMISSION_ITEM"
    ADD CONSTRAINT "DELIVERABLE_SUBMISSION_ITEM_task_id_deliverable_no_fkey"
    FOREIGN KEY ("task_id", "deliverable_no") REFERENCES "DELIVERABLE"("task_id", "deliverable_no") ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE "DELIVERABLE_SUBMISSION_ITEM"
    ADD CONSTRAINT "DELIVERABLE_SUBMISSION_ITEM_task_id_definition_id_fkey"
    FOREIGN KEY ("task_id", "definition_id") REFERENCES "TASK_DELIVERABLE_DEFINITION"("task_id", "definition_id") ON DELETE CASCADE ON UPDATE CASCADE;
